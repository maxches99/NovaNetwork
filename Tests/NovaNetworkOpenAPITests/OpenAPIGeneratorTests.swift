// MARK: - T-27.1 unchanged runtime behavior

/// Records the requests the client hands to the transport.
private actor RecordingTransport: NetworkTransport {
    private(set) var requests: [APIRequest] = []
    private let body: Data

    init(body: Data) {
        self.body = body
    }

    func execute(_ request: APIRequest) async throws -> NetworkResponse {
        requests.append(request)
        return NetworkResponse(statusCode: 200, headers: ["Content-Type": "application/json"], body: body)
    }

    func recorded() -> [APIRequest] { requests }
}

@Suite
struct GeneratedEndpointExecutionTests {
    @Test
    func aGeneratedEndpointExecutesExactlyLikeItsHandWrittenEquivalent() async throws {
        let payload = Data(#"{"id":7,"name":"Ada"}"#.utf8)
        let generatedTransport = RecordingTransport(body: payload)
        let handWrittenTransport = RecordingTransport(body: payload)

        let generatedClient = NetworkClient(transport: generatedTransport)
        let handWrittenClient = NetworkClient(transport: handWrittenTransport)

        let generated = try await generatedClient.execute(
            endpoint: GetPetById(petId: 7),
            authScope: "petstore",
            decoder: PetstoreAPI.makeDecoder()
        )

        let handWritten = try await handWrittenClient.execute(
            endpoint: AnyEndpoint(
                request: APIRequest(
                    method: .get,
                    url: URL(string: "https://api.petstore.example.com/v1/pets/7")!
                ),
                response: Pet.self
            ),
            authScope: "petstore",
            decoder: PetstoreAPI.makeDecoder()
        )

        let generatedRequests = await generatedTransport.recorded()
        let handWrittenRequests = await handWrittenTransport.recorded()

        #expect(generated == handWritten)
        #expect(generatedRequests.count == 1)
        #expect(generatedRequests[0].url == handWrittenRequests[0].url)
        #expect(generatedRequests[0].method == handWrittenRequests[0].method)
        #expect(generatedRequests[0].headers == handWrittenRequests[0].headers)
        #expect(generatedRequests[0].queryItems == handWrittenRequests[0].queryItems)
    }
}
