        #expect(warning?.message.contains("reference cycle") == true)
        #expect(result.source.contains("public var parent: Indirect<Pet>?"))
    }

    @Test
    func anAllOfCycleBetweenTwoSchemasIsReportedInsteadOfLoopingForever() throws {
        let spec = """
        openapi: 3.1.0
        info: {title: Cycles, version: 1.0.0}
        paths: {}
        components:
          schemas:
            A:
              allOf:
                - $ref: "#/components/schemas/B"
            B:
              allOf:
                - $ref: "#/components/schemas/A"
        """

        let result = try OpenAPIGenerator.generate(specText: spec)

        #expect(result.warnings.contains { $0.message.contains("Reference cycle") })
    }

    @Test
    func aDocumentWithoutServersTakesTheBaseURLAsAnInitializerParameter() throws {
        let spec = """
        openapi: 3.0.3
        info: {title: Serverless, version: 1.0.0}
        paths:
          /ping:
            get:
              operationId: ping
              responses:
                "204": {description: Pong.}
        """

        let result = try OpenAPIGenerator.generate(specText: spec)

        #expect(result.warnings.contains { $0.location == "#/servers" })
        #expect(result.source.contains("public var baseURL: URL"))
        #expect(result.source.contains("public init(baseURL: URL)"))
    }

    @Test
    func aNonJSONPayloadIsReportedRatherThanGeneratedWrong() throws {
        let spec = """
        openapi: 3.1.0
